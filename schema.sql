CREATE TABLE IF NOT EXISTS tasks (
  id TEXT PRIMARY KEY,
  wbs TEXT NOT NULL DEFAULT '',
  name TEXT NOT NULL,
  start TEXT NOT NULL,
  end TEXT NOT NULL,
  duration INTEGER NOT NULL,
  dependencies TEXT NOT NULL DEFAULT '[]',
  parent_id TEXT,
  progress INTEGER NOT NULL DEFAULT 0,
  color TEXT,
  sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS column_widths (
  id TEXT PRIMARY KEY DEFAULT 'default',
  wbs INTEGER NOT NULL DEFAULT 60,
  name INTEGER NOT NULL DEFAULT 200,
  start INTEGER NOT NULL DEFAULT 100,
  end INTEGER NOT NULL DEFAULT 100,
  duration INTEGER NOT NULL DEFAULT 60,
  action INTEGER NOT NULL DEFAULT 80
);

INSERT OR IGNORE INTO column_widths (id) VALUES ('default');
